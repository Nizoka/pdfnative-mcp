/**
 * Regenerate src/governance-embed.ts from the two governance files the
 * repository holds — `.github/ai-governance.json` (the machine-readable
 * policy) and `.github/AGENT_RULES.md` (the protocol) — so the server can
 * serve the contract to an agent on a host that cannot read the repository.
 *
 *   npm run agents:governance
 *
 * verify:docs (rule governance-embed) fails when either file and the module
 * differ: edit the file, run this, commit both.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lf = (p: string): string => readFileSync(join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');

export function renderGovernanceEmbed(policy: string, rules: string): string {
    return [
        '/**',
        ' * The AI-governance contract, embedded (1.8.0).',
        ' *',
        ' * Byte-for-byte copies of .github/ai-governance.json (the machine-readable',
        ' * policy) and .github/AGENT_RULES.md (the protocol an agent follows), served',
        ' * as the resources pdfnative://governance/policy and pdfnative://governance/rules',
        ' * so an agent on a remote host — which cannot read the repository — gets the',
        ' * same contract the repository holds. verify:docs (rule governance-embed) fails',
        ' * when either file drifts from this module: edit the file, then regenerate with',
        ' * npm run agents:governance.',
        ' *',
        ' * GENERATED by scripts/build-governance-embed.ts — do not edit by hand.',
        ' */',
        '',
        '/** .github/ai-governance.json, verbatim. */',
        `export const AI_GOVERNANCE_POLICY_JSON = ${JSON.stringify(policy)};`,
        '',
        '/** The parsed policy. */',
        'export const AI_GOVERNANCE_POLICY = JSON.parse(AI_GOVERNANCE_POLICY_JSON) as Record<string, unknown>;',
        '',
        '/** .github/AGENT_RULES.md, verbatim. */',
        `export const AGENT_RULES_TEXT = ${JSON.stringify(rules)};`,
        '',
    ].join('\n');
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const rendered = renderGovernanceEmbed(lf('.github/ai-governance.json'), lf('.github/AGENT_RULES.md'));
    writeFileSync(join(ROOT, 'src', 'governance-embed.ts'), rendered);
    process.stderr.write('src/governance-embed.ts regenerated\n');
}
